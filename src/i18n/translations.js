const englishLiteralLookup = Object.entries(translations.en).reduce(
  (lookup, [key, englishValue]) => {
    if (typeof englishValue === 'string' && englishValue) {
      lookup[englishValue] = translations.hi[key] || englishValue;
    }
    return lookup;
  },
  {},
);

/**
 * Translate an exact interface string. Unknown copy deliberately falls back to
 * the original English text instead of displaying a missing key or crashing.
 */
export function translateLiteral(value, language = 'en') {
  if (typeof value !== 'string' || language !== 'hi') {
    return value;
  }

  const trimmed = value.trim();
  if (!trimmed) {
    return value;
  }

  const translated =
    literalTextTranslations[trimmed] || englishLiteralLookup[trimmed];
  if (!translated) {
    return value;
  }

  const leading = value.match(/^\s*/)?.[0] || '';
  const trailing = value.match(/\s*$/)?.[0] || '';
  return `${leading}${translated}${trailing}`;
}

export function getTranslation(lang = 'en') {
  return translations[lang] || translations.en;
}

export function useTranslation() {
  const {language} = useSettings();
  const dict = translations[language] || translations.en;

  function t(key, fallback = '') {
    return dict[key] || fallback || key;
  }

  return {t, lang: language, dict};
}

export default translations;
